void TextRenderer::drawText(Renderer* renderer, const std::string& text, float x, float y, float scale, Vec3 color) {
    float charW = scale * 0.04f;
    float charH = scale * 0.06f;
    float spacing = charW * 1.5f;

    for (size_t i = 0; i < text.size(); i++) {
        char c = text[i];
        if (c < 32 || c > 90) continue;

        int fontIndex = c - 32;
        float cx = x + i * spacing;

        // Draw each pixel of the character
        for (int row = 0; row < 7; row++) {
            for (int col = 0; col < 5; col++) {
                if (font[fontIndex][row] & (1 << (4 - col))) {
                    float px = cx + col * charW / 5.0f;
                    float py = y - row * charH / 7.0f;

                    // Draw pixel as a small quad
                    Vertex verts[] = {
                        Vertex(Vec3(px, py, 0), color),
                        Vertex(Vec3(px + charW / 5.0f, py, 0), color),
                        Vertex(Vec3(px + charW / 5.0f, py + charH / 7.0f, 0), color),
                        Vertex(Vec3(px, py + charH / 7.0f, 0), color),
                    };
                    renderer->drawQuad(verts);
                }
            }
        }
    }
}

void TextRenderer::drawTextCentered(Renderer* renderer, const std::string& text, float y, float scale, Vec3 color) {
    float width = getTextWidth(text, scale);
    drawText(renderer, text, -width / 2.0f, y, scale, color);
}

float TextRenderer::getTextWidth(const std::string& text, float scale) {
    return text.size() * scale * 0.04f * 1.5f;
}
